export function autoFix(text: string): string {
  let fixed = text;
  for (const [from, to] of FIX_MAP) {
    const re = new RegExp(from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi");
    fixed = fixed.replace(re, to);
  }
  return fixed;
}

